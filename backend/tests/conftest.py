def write_sample_config(path: Path) -> None:
    """The example configuration, plus a ``Zines`` library with no titles.

    The example file is the canonical one, so the tests exercise exactly what a
    user is handed; ``Zines`` is added on top of it so that a library whose
    titles are derived rather than configured is covered too.
    """
    config = yaml.safe_load(EXAMPLE_CONFIG.read_text("utf-8"))
    config["libraries"].append({"name": "Zines", "path": "Zines", "kind": "magazine"})
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(config, sort_keys=False, allow_unicode=True), "utf-8")


