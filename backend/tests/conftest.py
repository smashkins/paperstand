REPO_ROOT = Path(__file__).resolve().parents[2]
GENERATOR_PATH = REPO_ROOT / "scripts" / "make_sample_library.py"
EXAMPLE_CONFIG = REPO_ROOT / "paperstand.example.yml"

#: Fixed "today", so that the generated library never moves under the tests.
SAMPLE_TODAY = dt.date(2026, 3, 17)
SAMPLE_DAYS = 14


@dataclass(frozen=True)
class SampleLibrary:
    """A generated library, with the generator's own per-layout tally."""

    root: Path
    counts: Counter[str]
    today: dt.date

    @property
    def newspaper_files(self) -> int:
        """PDFs written under ``Newspapers/``."""
        return self.counts["Newspapers/YYYY/MM/DD"]

    @property
    def magazine_files(self) -> int:
        """PDFs written under ``Magazines/``, in either layout."""
        return self.counts["Magazines/<Title>"] + self.counts["Magazines/YYYY/<Title>/MM"]

    @property
    def zine_files(self) -> int:
        """PDFs written under ``Zines/``."""
        return self.counts["Zines (flat)"]

    @property
    def catalogued_files(self) -> int:
        """Every PDF a scan is expected to catalogue."""
        return self.newspaper_files + self.magazine_files + self.zine_files

    @property
    def ignored_files(self) -> int:
        """Files the walker must never yield."""
        return self.counts["ignored"]

    def path(self, rel_path: str) -> Path:
        """An absolute path inside the library."""
        return self.root / rel_path


def load_generator() -> ModuleType:
    """Import ``scripts/make_sample_library.py`` as a module."""
    if "make_sample_library" in sys.modules:
        return sys.modules["make_sample_library"]
    spec = importlib.util.spec_from_file_location("make_sample_library", GENERATOR_PATH)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["make_sample_library"] = module
    spec.loader.exec_module(module)
    return module


def generate_sample_library(out: Path, today: dt.date = SAMPLE_TODAY) -> SampleLibrary:
    """Write the sample library into ``out`` and report what went into it."""
    generator = load_generator()
    out.mkdir(parents=True, exist_ok=True)
    (out / generator.MARKER_NAME).write_text(generator.MARKER_TEXT, encoding="utf-8")
    builder = generator.LibraryBuilder(out)
    generator.build_newspapers(builder, today, SAMPLE_DAYS)
    generator.build_magazines(builder, today.year)
    generator.build_zines(builder, today.year)
    generator.build_noise(builder, today)
    counts: Counter[str] = builder.counts
    return SampleLibrary(root=out, counts=counts, today=today)


