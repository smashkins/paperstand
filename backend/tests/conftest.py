def quiet_settings(library: Path, data: Path, **overrides: Any) -> Settings:
    """Settings that never scan on their own, so tests decide when they do."""
    values: dict[str, Any] = {
        "library": library,
        "data": data,
        "config": None,
        "static": None,
        "scan_on_start": False,
        "scan_interval": 0,
        "cover_workers": 2,
    }
    values.update(overrides)
    return Settings(**values)


@pytest.fixture(scope="session")
def scanned_data(sample_source: SampleLibrary, tmp_path_factory: pytest.TempPathFactory) -> Path:
    """A ``/data`` holding the sample library already catalogued.

    Scanning means opening a hundred PDFs, so it is done once for the whole
    session and copied per test. The catalogue only ever refers to a file by its
    path *relative* to the library root, so the copy is just as valid against
    each test's private copy of the library as it was against the original.
    """
    data = tmp_path_factory.mktemp("scanned") / "data"
    data.mkdir(parents=True)
    settings = quiet_settings(sample_source.root, data)
    write_sample_config(settings.config_path)
    result = scan_once(settings)
    assert result.status == "ok", result.message
    assert result.added > 0
    return data


