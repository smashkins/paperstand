"""Shared pytest fixtures.

The scanner is tested against the real sample library, generated by
``scripts/make_sample_library.py`` with a fixed ``--today`` so that two runs
produce the same names, the same dates and the same bytes. The generator is
imported rather than shelled out to, which gives the tests its own per-layout
tally: every count asserted below is derived from that tally instead of being
typed out by hand.

The library is built once per session and copied per test, because several tests
delete files, touch them or append to them.
"""

